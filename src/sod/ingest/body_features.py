"""Numeric features from post bodies (rendered HTML) and titles.

Computed during ingest so the raw text never needs to be stored. Regex-based on
purpose: an HTML parser is far too slow for ~60M Stack Overflow posts, and post
HTML is generated by Stack Exchange's renderer, so it is regular.
"""

from __future__ import annotations

import html
import re

_PRE = re.compile(r"<pre\b[^>]*>(.*?)</pre>", re.S | re.I)
_INLINE_CODE = re.compile(r"<code\b", re.I)
_LINK = re.compile(r"<a\s[^>]*\bhref=", re.I)
_IMAGE = re.compile(r"<img\b", re.I)
# Block-level tags become a space so "<p>a</p><p>b</p>" reads "a b";
# inline tags are removed so "x.<code>reverse</code>()" stays "x.reverse()".
_BLOCK_TAG = re.compile(
    r"</?(?:p|div|li|ol|ul|blockquote|h[1-6]|br|hr|tr|td|th|table|thead|tbody|dl|dt|dd)\b[^>]*>",
    re.I,
)
_ANY_TAG = re.compile(r"<[^>]+>")
_WS = re.compile(r"\s+")

EMPTY = {
    "body_chars": 0,
    "text_chars": 0,
    "code_chars": 0,
    "n_code_blocks": 0,
    "n_inline_code": 0,
    "n_links": 0,
    "n_images": 0,
}


def body_features(body: str | None) -> dict[str, int]:
    if not body:
        return dict(EMPTY)

    blocks = _PRE.findall(body)
    code_chars = sum(len(html.unescape(_ANY_TAG.sub("", b))) for b in blocks)
    prose = _PRE.sub(" ", body)

    text = _ANY_TAG.sub("", _BLOCK_TAG.sub(" ", prose))
    text = _WS.sub(" ", html.unescape(text)).strip()

    return {
        "body_chars": len(body),
        "text_chars": len(text),
        "code_chars": code_chars,
        "n_code_blocks": len(blocks),
        "n_inline_code": len(_INLINE_CODE.findall(prose)),
        "n_links": len(_LINK.findall(body)),
        "n_images": len(_IMAGE.findall(body)),
    }


def title_features(title: str | None) -> dict[str, int]:
    if not title:
        return {"title_chars": 0, "title_words": 0}
    stripped = title.strip()
    return {"title_chars": len(stripped), "title_words": len(stripped.split())}
